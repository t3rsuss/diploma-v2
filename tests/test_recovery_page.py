import pathlib

from streamlit.testing.v1 import AppTest

from analyze_all import analyze_set
from demo import cfg1

ROOT = pathlib.Path(__file__).resolve().parents[1]
PAGE = ROOT / "views" / "recovery.py"


def test_recovery_page_opens_without_browser():
    app = AppTest.from_file(str(PAGE), default_timeout=30).run()
    assert not app.exception
    assert len(app.title) == 1
    assert app.title[0].value == "Відновлення структури за програмою-читачем"


def test_recovery_page_displays_analysis_and_switches_file(
    tmp_path, monkeypatch,
):
    monkeypatch.setattr(cfg1, "OUT", tmp_path / "samples")
    monkeypatch.setattr(cfg1, "LABELS", tmp_path / "labels.json")
    folder, _ = cfg1.generate(n_benign=5, n_mal=0)
    audit = []
    reports = analyze_set(
        [str(folder)],
        reader="demo.cfg1:parse_file",
        limit=5,
        sample_audit=audit,
    )

    assert len(reports) == 5
    assert all(r["status"] == "ok" for r in reports)

    for index, report in enumerate(reports):
        report["input_id"] = f"sample_{index:03d}.bin"

    payload = {
        "reader": "CFG1 — демонстраційний читач",
        "run_error": None,
        "input_manifest": [
            {"name": r["file"], "sha256": r["sha256"]}
            for r in reports
        ],
        "upload_audit": [],
        "sample_audit": audit,
        "limitations": ["Test payload generated by the real analysis core."],
        "reports": reports,
    }

    app = AppTest.from_file(str(PAGE), default_timeout=30)
    app.session_state["joint_recovery_report"] = payload
    app.run()

    assert not app.exception
    assert [m.value for m in app.metric] == ["5", "5", "0"]
    assert len(app.dataframe) >= 1
    assert len(app.dataframe[0].value) == len(reports[0]["fields"])
    evidence_tables = [
        widget.value for widget in app.dataframe
        if "підтримка правила" in widget.value.columns
    ]
    expected_evidence = reports[0]["length_evidence"]
    assert expected_evidence
    assert len(evidence_tables) == 1
    table = evidence_tables[0]
    assert table["значення"].tolist() == [
        item["value"] for item in expected_evidence
    ]
    assert table["збігів"].tolist() == [
        item["matching_events"] for item in expected_evidence
    ]
    assert table["збіг у цьому файлі"].tolist() == [
        item["local_read_match"] for item in expected_evidence
    ]

    selector = next(
        widget for widget in app.selectbox
        if widget.label == "Файл для перегляду структури"
    )
    selector.select(reports[1]["input_id"]).run()

    assert not app.exception
    assert len(app.dataframe[0].value) == len(reports[1]["fields"])
    evidence_tables = [
        widget.value for widget in app.dataframe
        if "підтримка правила" in widget.value.columns
    ]
    expected_evidence = reports[1]["length_evidence"]
    assert expected_evidence
    assert len(evidence_tables) == 1
    table = evidence_tables[0]
    assert table["значення"].tolist() == [
        item["value"] for item in expected_evidence
    ]
    assert table["збігів"].tolist() == [
        item["matching_events"] for item in expected_evidence
    ]
    assert table["збіг у цьому файлі"].tolist() == [
        item["local_read_match"] for item in expected_evidence
    ]
    assert any(
        reports[1]["sha256"] in caption.value
        for caption in app.caption
    )
